    private fun translateBySegments(text: String): String {
        if (!text.any { it in '\u4e00'..'\u9fff' }) return text
        var result = text
        for ((from, to) in segmentTranslations.sortedByDescending { it.first.length }) {
            result = result.replace(from, to)
        }
        return if (result.any { it in '\u4e00'..'\u9fff' }) text else result
    }

