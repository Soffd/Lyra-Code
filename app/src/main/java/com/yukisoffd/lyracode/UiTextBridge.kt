    fun isEnglish(): Boolean {
        return when (AppSettings.normalizeLanguageMode(languageMode)) {
            AppSettings.LANGUAGE_EN -> true
            AppSettings.LANGUAGE_ZH_CN -> false
            else -> Locale.getDefault().language.equals("en", ignoreCase = true)
        }
    }

    fun translate(text: String): String {
        if (!isEnglish()) return text
        translations[text]?.let { return it }
        val dynamic = translateDynamic(text)
        if (dynamic != text) return dynamic
        return translateBySegments(text)
    }

